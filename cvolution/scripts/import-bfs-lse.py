"""
Converts BFS LSE table T17 (Monatlicher Bruttolohn nach Berufsgruppen, Lebensalter und Geschlecht)
into src/data/bfs-lse-berufsgruppen.ts.

Source: https://dam-api.bfs.admin.ch/hub/api/dam/assets/36355224/master (sheet "2024")
Usage:  python3 scripts/import-bfs-lse.py [path/to/t17.xlsx] [sheet]
Values in [brackets] are statistically less reliable (BFS); "*" means too few observations.
"""
import json, re, sys
from pathlib import Path
import openpyxl

ROOT = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "scripts/data/bfs-lse-t17.xlsx"
sheet = sys.argv[2] if len(sys.argv) > 2 else "2024"

ws = openpyxl.load_workbook(src, read_only=True, data_only=True)[sheet]

def cell(value):
    if value is None:
        return None
    text = str(value).strip()
    if text in ("*", "", "-"):
        return None
    uncertain = text.startswith("[")
    number = int(round(float(re.sub(r"[\[\]'’ ]", "", text))))
    return {"v": number, "u": True} if uncertain else {"v": number}

COLS = ["total", "women", "men", "u29", "u29Women", "u29Men", "a30to49", "a30to49Women", "a30to49Men", "o50", "o50Women", "o50Men"]
groups = []
for row in ws.iter_rows(values_only=True):
    padded = (list(row) + [None] * 15)[:15]
    code, name, values = padded[0], padded[1], padded[3:15]  # column C is an empty spacer
    code = str(code).strip() if code is not None else ""
    if not (code == "" and str(name).strip().upper() == "TOTAL") and not re.fullmatch(r"\d{1,2}", code):
        continue
    entry = {"code": code or "total", "name": " ".join(str(name).split())}
    entry.update({key: cell(val) for key, val in zip(COLS, values)})
    groups.append(entry)

out = ROOT / "src/data/bfs-lse-berufsgruppen.ts"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(
    "// Generated by scripts/import-bfs-lse.py from BFS LSE table T17. Do not edit by hand.\n"
    "// Monthly gross wage (median), full-time equivalent (40 h), incl. 1/12 of the 13th salary,\n"
    "// private and public sector combined. u = statistically less reliable value (BFS brackets).\n"
    f"export const LSE_YEAR = {int(sheet)};\n"
    "export const LSE_SOURCE_URL = \"https://www.bfs.admin.ch/bfs/de/home/statistiken/arbeit-erwerb/loehne-erwerbseinkommen-arbeitskosten/lohnstruktur/berufsgruppen.html\";\n\n"
    "export type LseValue = { v: number; u?: boolean } | null;\n"
    "export type LseGroup = { code: string; name: string } & Record<\n"
    "  " + " | ".join(f'\"{c}\"' for c in COLS) + ",\n  LseValue\n>;\n\n"
    f"export const LSE_GROUPS: LseGroup[] = {json.dumps(groups, ensure_ascii=False, indent=2)};\n",
    encoding="utf-8",
)
print(f"{len(groups)} rows -> {out.relative_to(ROOT)}")
