"""
Converts BFS LSE table T1_gr (Monatlicher Bruttolohn nach Wirtschaftszweigen und Grossregionen,
privater und öffentlicher Sektor zusammen) into src/data/bfs-lse-grossregionen.ts.

Source: https://dam-api.bfs.admin.ch/hub/api/dam/assets/36196182/master (sheet "2024")
Usage:  python3 scripts/import-bfs-lse-regionen.py [path/to/t1-gr.xlsx] [sheet]
Values in [brackets] are statistically less reliable (BFS); "*" means too few observations, "-" no data.
"""
import json, re, sys
from pathlib import Path
import openpyxl

ROOT = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "scripts/data/bfs-lse-t1-gr.xlsx"
sheet = sys.argv[2] if len(sys.argv) > 2 else "2024"

ws = openpyxl.load_workbook(src, read_only=True, data_only=True)[sheet]

REGIONS = ["schweiz", "genferseeregion", "espaceMittelland", "nordwestschweiz", "zuerich", "ostschweiz", "zentralschweiz", "tessin"]

def cell(value):
    if value is None:
        return None
    text = str(value).strip()
    if text in ("*", "", "-"):
        return None
    uncertain = text.startswith("[")
    number = int(round(float(re.sub(r"[\[\]'’ ]", "", text))))
    return {"v": number, "u": True} if uncertain else {"v": number}

rows = []
for row in ws.iter_rows(values_only=True):
    padded = (list(row) + [None] * 10)[:10]
    code, name, values = padded[0], padded[1], padded[2:10]
    code = str(code).strip() if code is not None else ""
    name = " ".join(str(name).split()) if name is not None else ""
    if name.upper() == "TOTAL":
        code = "total"
    elif not re.fullmatch(r"\d{2}(?:[-,]\s?\d{2})*", code):
        continue
    entry = {"code": code, "name": name}
    entry.update({key: cell(val) for key, val in zip(REGIONS, values)})
    rows.append(entry)

out = ROOT / "src/data/bfs-lse-grossregionen.ts"
out.write_text(
    "// Generated by scripts/import-bfs-lse-regionen.py from BFS LSE table T1_gr. Do not edit by hand.\n"
    "// Monthly gross wage (median), full-time equivalent (40 h), incl. 1/12 of the 13th salary,\n"
    "// private and public sector combined, by economic branch (NOGA08) and Grossregion.\n"
    "// u = statistically less reliable value (BFS brackets).\n"
    f"export const LSE_REGION_YEAR = {int(sheet)};\n"
    "export const LSE_REGION_SOURCE_URL = \"https://www.bfs.admin.ch/bfs/de/home/statistiken/arbeit-erwerb/loehne-erwerbseinkommen-arbeitskosten/lohnstruktur/grossregionen.html\";\n\n"
    "export type LseRegionValue = { v: number; u?: boolean } | null;\n"
    "export type LseRegionKey = " + " | ".join(f'\"{r}\"' for r in REGIONS) + ";\n"
    "export type LseBranchRow = { code: string; name: string } & Record<LseRegionKey, LseRegionValue>;\n\n"
    f"export const LSE_REGION_ROWS: LseBranchRow[] = {json.dumps(rows, ensure_ascii=False, indent=2)};\n",
    encoding="utf-8",
)
print(f"{len(rows)} rows -> {out.relative_to(ROOT)}")
